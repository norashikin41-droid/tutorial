// Helper untuk menyusun rumus mengikut kategori bagi mod paparan terperinci
export const getFormulasByCategory = () => {
  const categoriesMap: Record<string, OfficialFormulaItem[]> = {};
  OFFICIAL_GCMT_FORMULAS.forEach((item) => {
    if (!categoriesMap[item.category]) {
      categoriesMap[item.category] = [];
    }
    categoriesMap[item.category].push(item);
  });
  return Object.entries(categoriesMap).map(([category, formulas]) => ({
    category,
    formulas: formulas.map((f) => ({
      name: `[No. ${f.num}] ${f.title}`,
      formula: f.formula,
      rawItem: f,
    })),
  }));
};
